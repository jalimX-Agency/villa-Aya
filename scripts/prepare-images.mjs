// Reads the client's JPEGs, classifies them by the 1-based index of the sorted file list,
// and writes optimised WebP (full + thumb) to public/images + a typed manifest.
import sharp from "sharp";
import { readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const SRC = process.argv[2];
const OUT = "public/images";

const GROUPS = {
  exterieur: [2, 27, 28, 32],
  piscine: [36, 35, 34, 44, 5],
  terrasse: [40],
  hammam: [18, 1, 19],
  "salle-de-sport": [12, 11, 13],
  priere: [45],
  "salon-marocain": [3, 37],
  "salon-chalet": [41, 42, 43, 10, 9, 7, 25, 26],
  "salon-rdc": [31, 33, 39],
  cuisine: [29, 30],
  "chambre-chalet": [21, 22, 23, 8],
  "chambre-rose": [38, 16, 14, 15, 17],
  "salle-de-bain": [20, 24],
  "petit-dejeuner": [4, 6],
};

const files = readdirSync(SRC).filter((f) => f.endsWith(".jpeg")).sort();
mkdirSync(OUT, { recursive: true });
const manifest = {};
const map = [];
const used = new Set();

for (const [group, idxs] of Object.entries(GROUPS)) {
  manifest[group] = [];
  let n = 1;
  for (const idx of idxs) {
    if (used.has(idx)) throw new Error(`duplicate ${idx}`);
    used.add(idx);
    const file = files[idx - 1];
    const name = `${group}-${String(n++).padStart(2, "0")}`;
    const img = sharp(join(SRC, file)).rotate();
    const meta = await img.clone().metadata();
    const w = meta.autoOrient?.width ?? meta.width, h = meta.autoOrient?.height ?? meta.height;
    await img.clone().webp({ quality: 80 }).toFile(join(OUT, `${name}.webp`));
    await img.clone().resize({ width: 640, withoutEnlargement: true }).webp({ quality: 72 }).toFile(join(OUT, `${name}-sm.webp`));
    manifest[group].push({ src: `/images/${name}.webp`, thumb: `/images/${name}-sm.webp`, width: w, height: h });
    map.push(`| ${idx} | ${file} | ${name}.webp |`);
  }
}
const unused = files.map((_, i) => i + 1).filter((i) => !used.has(i));
if (unused.length) console.warn("Unclassified:", unused);

writeFileSync(
  "src/content/images.ts",
  `// Generated by scripts/prepare-images.mjs — do not edit by hand.\nexport type Img = { src: string; thumb: string; width: number; height: number };\nexport const images = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, readonly Img[]>;\n`,
);
writeFileSync("docs/images-map.md", `# Image map\n\n| # | Original | New |\n|---|---|---|\n${map.join("\n")}\n`);
console.log("done", used.size, "images");
